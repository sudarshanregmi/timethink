async def get_gt_keywords(llm, question, groundtruth, callbacks):
    cache = load_cache()
    cache_key = json.dumps(question, ensure_ascii=False) + '|||' + json.dumps(groundtruth, ensure_ascii=False)

    if cache_key in cache:
        return cache[cache_key]

    # Use the LLM to generate gt_keywords
    prompt = GTKeywordsPrompt()
    input_data = GTKeywordsInput(question=question, ground_truth=groundtruth)
    
    result = await prompt.generate(
        llm=llm, 
        data=input_data, 
        callbacks=callbacks
    )
    
    gt_keywords = []
    if result.gt_keywords:
        # Remove keywords from questions if they appear there (custom logic preserved from original)
        for key in result.gt_keywords:
            if key.lower() not in question.lower() or key.lower() in groundtruth.lower():
                gt_keywords.append(key)

    cache[cache_key] = gt_keywords
    save_cache(cache)

    return gt_keywords


@dataclass
class AnswerCorrectness(MetricWithLLM, MetricWithEmbeddings, SingleTurnMetric):
    name: str = "answer_correctness"
    answer_prompt: PydanticPrompt = field(default_factory=OverlapPrompt)
    weights: list[float] = field(default_factory=lambda: [1.0, 0.0])
    keyword_matching_threshold: float = field(default_factory=lambda: 0.6)
    answer_similarity: t.Optional[AnswerSimilarity] = None
    answer_detail: dict = field(default_factory=dict)

    def __post_init__(self):
        if len(self.weights) != 2:
            raise ValueError("Expects a list of two weights. First for factuality, second for semantic similarity")
        if all([w == 0 for w in self.weights]):
            raise ValueError("At least one weight must be non-zero")

    def init(self, run_config: RunConfig):
        super().init(run_config)
        if self.answer_similarity is None and self.weights[1] != 0:
            self.answer_similarity = AnswerSimilarity(
                embeddings=self.embeddings
            )

    def match(self, arr, k):
        for item in arr:
            if difflib.SequenceMatcher(None, item, k).ratio() >= self.keyword_matching_threshold:
                return True
        return False

    def _compute_statement_presence(self, gt_keywords, prediction: OverlapOutput, question: str) -> float:
        overlapping_keywords = prediction.overlapping_keywords if prediction else []
        
        if gt_keywords is None:
            gt_keywords = []
            
        gt_keywords_lower = [k.lower() for k in gt_keywords]
        overlapping_keywords_lower = [k.lower() for k in overlapping_keywords]
        
        self.answer_detail[question] = {'answer_keywords': '|'.join(overlapping_keywords_lower)}
        
        # Filter overlapping keywords based on match threshold
        valid_overlaps = [k for k in overlapping_keywords_lower if self.match(gt_keywords_lower, k)]
        
        num_ok = len(valid_overlaps)
        num_all = len(gt_keywords)
        
        self.answer_detail[question].update({
            'gt_keywords': '|'.join(gt_keywords_lower),
            'overlapping_keywords': '|'.join(valid_overlaps),
            'num_ok': int(num_ok),
            'num_all': int(num_all)
        })
        
        if num_all > 0:
            score = min(num_ok / num_all, 1.0)
        else:
            score = np.nan
            
        return score

    async def _single_turn_ascore(self, sample: SingleTurnSample, callbacks: t.Any) -> float:
        row = sample.to_dict()
        return await self._ascore(row, callbacks)

    async def _ascore(self, row: dict, callbacks: t.Any) -> float:
        assert self.llm is not None, "LLM must be set"
        
        # Map standard Ragas columns if necessary, or expect user_input/response/reference
        q = row.get("user_input")
        a = row.get("response")
        g = row.get("reference")
        
        if not a or not a.strip():
            return 0.0

        gt_keywords = await get_gt_keywords(self.llm, q, g, callbacks)
 
        input_data = OverlapInput(
            question=q,
            gt_keywords=gt_keywords,
            answer=a
        )
        
        prediction = await self.answer_prompt.generate(
            llm=self.llm, 
            data=input_data, 
            callbacks=callbacks
        )

        f1_score = self._compute_statement_presence(gt_keywords, prediction, q)

        similarity_score = 0.0
        if self.weights[1] != 0:
            assert self.answer_similarity is not None, "AnswerSimilarity must be set"
            # Re-use the row, assuming keys are correct for AnswerSimilarity (user_input, response, reference)
            # Create a sample object for the internal metric call
            sim_sample = SingleTurnSample(user_input=q, response=a, reference=g)
            similarity_score = await self.answer_similarity.single_turn_ascore(
                sim_sample, callbacks=callbacks
            )

        if q not in self.answer_detail:
            self.answer_detail[q] = {}
            
        self.answer_detail[q]['answer_similarity'] = float(similarity_score)
        self.answer_detail[q]['keywords_prediction'] = str(prediction.model_dump())
        
        score = np.average(
            [f1_score, similarity_score],
            weights=self.weights,
        )

        return float(score)
