DATA_DIR = config.get('data_dir', 'data').rstrip('/')
CACHE_PATH = os.path.join(DATA_DIR, 'gt_cache.json')
CACHE_LOCK_PATH = CACHE_PATH.replace('.json', '.lock')

def load_cache():
    if os.path.exists(CACHE_PATH):
        with FileLock(CACHE_LOCK_PATH):
            with open(CACHE_PATH, 'r') as f:
                return json.load(f)
    return {}

def save_cache(cache):
    with FileLock(CACHE_LOCK_PATH):
        if os.path.exists(CACHE_PATH):
            with open(CACHE_PATH, 'r') as f:
                old = json.load(f)
            old.update(cache)  # new values overwrite old
            cache = old
        with open(CACHE_PATH, 'w') as f:
            json.dump(cache, f, ensure_ascii=False, indent=4)


class GTKeywordsInput(BaseModel):
    question: str
    ground_truth: str

class GTKeywordsOutput(BaseModel):
    gt_keywords: t.List[str]

class GTKeywordsPrompt(PydanticPrompt[GTKeywordsInput, GTKeywordsOutput]):
    name: str = "gt_keywords"
    instruction: str = """Given a question and the ground truth, extract the following information:
            "gt_keywords": Identify and return a list of keywords or phrases contained in the ground_truth. This list should only include the minimal combination of key points that directly answer the question, avoiding words unrelated to the question as much as possible. Only **1 or 2** keywords are needed in each list, and the keywords should be as concise as possible and **as short as possible**."""
    input_model = GTKeywordsInput
    output_model = GTKeywordsOutput
    examples = [
        (
            GTKeywordsInput(
                question="What is the overall trend of the CPU utilization metric?",
                ground_truth="The CPU utilization shows an increasing trend from timestep 0 to 150, followed by a steady period, and then a sharp decrease near timestep 200 indicating a possible anomaly or load drop."
            ),
            GTKeywordsOutput(gt_keywords=["increasing trend then steady then sharp decrease"])
        ),
        (
            GTKeywordsInput(
                question="Are memory usage and disk I/O correlated in terms of trend?",
                ground_truth="Both memory usage and disk I/O exhibit similar upward trends between timesteps 50 and 120, suggesting they are positively correlated during that period, likely due to increased application load."
            ),
            GTKeywordsOutput(gt_keywords=["positively correlated"])
        )
    ]

class OverlapInput(BaseModel):
    question: str
    gt_keywords: t.List[str]
    answer: str

class OverlapOutput(BaseModel):
    overlapping_keywords: t.List[str]

class OverlapPrompt(PydanticPrompt[OverlapInput, OverlapOutput]):
    name: str = "answer_correctness_step_2"
    instruction: str = """Given a question, an answer generated by the model, and the list of ground truth keywords (gt_keywords), extract the following information:
        "overlapping_keywords": From the list of "gt_keywords", identify any terms or phrases that also appear in the model's answer. These overlapping keywords indicate the points of agreement or coverage between the model's answer and the ground truth."""
    input_model = OverlapInput
    output_model = OverlapOutput
    examples =[
        (
            OverlapInput(
                question="What is the overall trend of the CPU utilization metric?",
                gt_keywords=["increasing trend", "steady", "sharp decrease"],
                answer="The CPU utilization metric shows an increasing trend at first, then becomes steady."
            ),
            OverlapOutput(overlapping_keywords=["increasing trend", "steady"])
        ),
        (
            OverlapInput(
                question="Are memory usage and disk I/O correlated?",
                gt_keywords=["positively correlated", "similar upward trends"],
                answer="Yes, they exhibit similar upward trends and are positively correlated."
            ),
            OverlapOutput(overlapping_keywords=["positively correlated", "similar upward trends"])
        )
    ]


# --- Description QA Extraction Models ---

class TrendSegment(BaseModel):
    segment_type: t.Optional[str] = Field(default=None, description="'increasing', 'decreasing', or 'steady'")
    start_point: t.Optional[t.Union[int, float]] = Field(default=None, description="Start point index")
    end_point: t.Optional[t.Union[int, float]] = Field(default=None, description="End point index")

class TrendExtraction(BaseModel):
    trend_type: t.Optional[str] = Field(default=None, description="Overall trend: 'increasing', 'decreasing', 'steady', or 'multiple'")
    start_value: t.Optional[float] = Field(default=None, description="Starting value of the time series")
    end_value: t.Optional[float] = Field(default=None, description="Ending value of the time series")
    amplitude: t.Optional[float] = Field(default=None, description="Overall amplitude/change of the trend")
    segments: t.Optional[t.List[TrendSegment]] = Field(default=None, description="List of trend segments if multiple")

class SeasonalExtraction(BaseModel):
    has_periodicity: bool = Field(description="Whether periodic fluctuation exists")
    seasonal_type: t.Optional[str] = Field(default=None, description="Type of periodicity if present")
    period: t.Optional[float] = Field(default=None, description="Period length")
    amplitude: t.Optional[float] = Field(default=None, description="Amplitude of periodic fluctuation")

class NoiseExtraction(BaseModel):
    noise_level: str = Field(description="'smooth' or 'noisy'")
    noise_strength: t.Optional[float] = Field(default=None, description="Noise strength as ratio of signal amplitude")

class LocalEvent(BaseModel):
    event_type: str = Field(description="Type of local fluctuation: 'spike', 'dip', 'shake', 'sudden increase', 'sudden decrease', etc.")
    position: t.Optional[t.Union[int, float]] = Field(default=None, description="Position (point number) where the event occurs")
    amplitude: t.Optional[float] = Field(default=None, description="Amplitude of the local event")
    explanation: t.Optional[str] = Field(default=None, description="Physical meaning or explanation of this specific local event, if provided in the text")

class LocalEventExtraction(BaseModel):
    events: List[LocalEvent] = Field(default_factory=list)

class DescriptionExtraction(BaseModel):
    """Combined extraction for all perspectives in a description QA response."""
    trend: t.Optional[TrendExtraction] = None
    seasonal: t.Optional[SeasonalExtraction] = None
    noise: t.Optional[NoiseExtraction] = None
    local: t.Optional[LocalEventExtraction] = None
    physical_explanation: t.Optional[str] = Field(default=None, description="Any physical meaning/significance explanation found in the text")


class DescriptionExtractionInput(BaseModel):
    text: str


class DescriptionExtractionPrompt(PydanticPrompt[DescriptionExtractionInput, DescriptionExtraction]):
    name: str = "description_extraction"
    instruction: str = """Extract structured time series description data from the following text.

IMPORTANT: Read the ENTIRE response holistically before extracting. Do NOT do raw keyword extraction.
Instead, logically reason about the content:
- If "spike" is mentioned in one sentence and "followed by increase" in another, understand them as related context.
- Synthesize scattered descriptions into coherent structured fields.

Only fill in perspectives that are actually discussed in the text. Leave others as null.

For trend: identify the overall type (increasing/decreasing/steady/multiple), start value, end value, amplitude, and any segments.
For seasonality/periodicity: identify whether periodicity exists, its type, period length, and amplitude.
For noise: identify the noise level category (smooth or noisy) and the noise strength value (ratio of signal amplitude).
For local characteristics: identify each local event with its type (spike, dip, shake, sudden increase, sudden decrease, etc.), approximate position, amplitude, and any explanation of physical meaning specific to that event.
For physical explanation: extract any text that explains the physical meaning or significance of the time series characteristics.

Return a valid JSON object matching the output schema."""
    input_model = DescriptionExtractionInput
    output_model = DescriptionExtraction


